  // アゲハ：四色型（Koshitaka et al. 2008）。紫外は紫がかった光で重ねる
  chou:    { name: "チョウ",   m: sat(1.12),                            uvw: [.45, 0, .65],  sub: "紫外から赤まで・四色型とされる" },
  // 鳥：四色型（Hart 2001）。紫外は同じく紫で重ねる
  tori:    { name: "鳥",       m: sat(1.25),                            uvw: [.4, 0, .7],    sub: "四色型・種によって紫外まで" },
  // ミツバチ：紫外・青・緑（Peitsch et al. 1992：約 340・435・540 nm）。表示は 紫外→青・青→緑・緑→赤
  hachi:   { name: "ハチ",     m: [.18, .85, .10, 0, .15, .85, 0, 0, .02], uvw: [0, 0, 1],    sub: "紫外・青・緑の三色型" },
  // 犬：二色型（Neitz, Geist & Jacobs 1989）。人の二色型の近似の行列（Machado et al. 2009）
